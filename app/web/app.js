function lineChart(cfg) {
  return (W, H) => {
    // On a 320px phone a fixed 44px gutter eats the plot; scale with width.
    const P = {l: Math.min(44, Math.max(30, W * 0.12)), r: 14, t: 14, b: 26};
    const w = W - P.l - P.r, h = H - P.t - P.b;
    const labels = cfg.labels || [], sets = cfg.series || [];
    const all = sets.flatMap(s => s.values);
    const min = cfg.min !== undefined ? cfg.min : Math.min(...all, 0);
    const max = Math.max(...all, 1) * 1.12;
    const x = i => P.l + (labels.length <= 1 ? w / 2 : (i / (labels.length - 1)) * w);
    const y = v => P.t + h - ((v - min) / (max - min || 1)) * h;
    let g = defs();
    for (let k = 0; k <= 4; k++) {
      const yy = P.t + (k / 4) * h, val = max - (k / 4) * (max - min);
      g += `<line class="gridline" x1="${P.l}" y1="${yy}" x2="${W - P.r}" y2="${yy}"/>`;
      g += `<text class="lbl" x="${P.l - 7}" y="${yy + 3}" text-anchor="end">${cfg.fmtY ? cfg.fmtY(val) : fmt(val, 0)}</text>`;
    }
    labels.forEach((l, i) => {
      if (labels.length > 9 && i % Math.ceil(labels.length / 7) !== 0 && i !== labels.length - 1) return;
      g += `<text class="lbl" x="${x(i)}" y="${H - 7}" text-anchor="middle">${esc(l)}</text>`;
    });
    if (cfg.band) {
      const up = cfg.band.upper.map((v, i) => `${x(i)},${y(v)}`).join(' ');
      const dn = cfg.band.lower.map((v, i) => `${x(i)},${y(v)}`).reverse().join(' ');
      g += `<polygon points="${up} ${dn}" fill="rgba(198,161,91,.18)" stroke="none"/>`;
    }
    sets.forEach((s, si) => {
      const pts = s.values.map((v, i) => `${x(i)},${y(v)}`).join(' ');
      const col = s.color || PALETTE[si];
      if (s.area && si === 0) g += `<polygon class="area" points="${P.l},${P.t + h} ${pts} ${W - P.r},${P.t + h}" fill="url(#goldFade)"/>`;
      g += `<g data-series="${si}"><polyline class="line" points="${pts}" stroke="${col}" ${s.dash ? 'stroke-dasharray="5 5"' : ''}/>`;
      s.values.forEach((v, i) => {
        if (s.dots !== false) g += `<circle cx="${x(i)}" cy="${y(v)}" r="2.6" fill="${col}" stroke="#0B0906" stroke-width="1.2"/>`;
      });
      g += '</g>';
    });
    labels.forEach((l, i) => {
      const half = w / Math.max(1, labels.length - 1) / 2;
      const tt = `<b>${esc(l)}</b><br>` + sets.map(s =>
        `${esc(s.name)}: <b>${fmt(s.values[i], cfg.decimals ?? 1)}</b>${cfg.unit || ''}`).join('<br>');
      g += `<rect class="hit" x="${x(i) - half}" y="${P.t}" width="${half * 2}" height="${h}" data-tt="${esc(tt)}"/>`;
    });
    g += `<line class="axis" x1="${P.l}" y1="${P.t + h}" x2="${W - P.r}" y2="${P.t + h}"/>`;
    return `<svg viewBox="0 0 ${W} ${H}" width="100%" height="100%">${g}</svg>`;
  };
}
function donutChart(items) {
  return (W, H) => {
    const cx = W / 2, cy = H / 2, R = Math.min(W, H) / 2 - 16, r = R * 0.61;
    const total = items.reduce((a, b) => a + (b.value || 0), 0) || 1;
    let ang = -Math.PI / 2, g = defs();
    items.forEach((it, i) => {
      const a2 = ang + (it.value / total) * Math.PI * 2;
      const large = a2 - ang > Math.PI ? 1 : 0;
      const p = (rad, a) => `${(cx + rad * Math.cos(a)).toFixed(2)},${(cy + rad * Math.sin(a)).toFixed(2)}`;
      const d = `M ${p(R, ang)} A ${R} ${R} 0 ${large} 1 ${p(R, a2)} L ${p(r, a2)} A ${r} ${r} 0 ${large} 0 ${p(r, ang)} Z`;
      const color = it.color || PALETTE[i % PALETTE.length];
      g += `<path d="${d}" fill="${color}" stroke="#0B0906" stroke-width="2" data-tt="${esc(`<b>${esc(it.label)}</b><br>${fmt(it.value, 1)}% share`)}"/>`;
      ang = a2;
    });
    g += `<text x="${cx}" y="${cy - 4}" text-anchor="middle" fill="#F3ECDD" font-family="Satoshi,Arial" font-weight="900" font-size="22">${items.length}</text>`;
    g += `<text x="${cx}" y="${cy + 14}" text-anchor="middle" fill="#B9AE9C" font-size="9" font-family="Inter,Arial" letter-spacing="1.4">TRACKED PLAYERS</text>`;
    return `<svg viewBox="0 0 ${W} ${H}" width="100%" height="100%">${g}</svg>`;
  };
}
function barChart(items, opts = {}) {
  return (W, H) => {
    // On a phone a left-hand label gutter leaves almost no room for the bar.
    // Switch to a stacked layout: label and value on top, full-width bar below.
    const compact = W < 420;
    const P = compact
      ? {l: 8, r: 8, t: 8, b: 8}
      : {l: Math.min(opts.labelWidth || 96, Math.max(52, W * 0.34)),
         r: Math.min(44, Math.max(20, W * 0.12)), t: 10, b: 8};
    const rowH = (H - P.t - P.b) / Math.max(1, items.length);
    const max = Math.max(...items.map(i => i.value), 1);
    const trackW = W - P.l - P.r;
    let g = defs();
    items.forEach((it, i) => {
      const tt = esc(`<b>${esc(it.label)}</b><br>${fmt(it.value, 1)}${opts.unit || ''}`);
      const value = `${fmt(it.value, opts.decimals ?? 1)}${opts.unit || ''}`;
      const color = it.color || PALETTE[i % PALETTE.length];
      if (compact) {
        // Truncate only the visible label; the tooltip keeps the full name.
        const maxChars = Math.max(8, Math.floor((W - 70) / 5.6));
        const short = it.label.length > maxChars
          ? it.label.slice(0, maxChars - 1) + '…' : it.label;
        const y = P.t + i * rowH;
        const barY = y + rowH * 0.52, barH = Math.max(6, rowH * 0.26);
        g += `<text class="lbl-b" x="${P.l}" y="${y + rowH * 0.38}" text-anchor="start">${esc(short)}</text>`;
        g += `<text class="lbl" x="${W - P.r}" y="${y + rowH * 0.38}" text-anchor="end">${value}</text>`;
        g += `<rect x="${P.l}" y="${barY}" width="${trackW}" height="${barH}" rx="3" fill="rgba(255,255,255,.045)"/>`;
        g += `<rect class="bar" x="${P.l}" y="${barY}" width="${Math.max(2, trackW * it.value / max)}" height="${barH}" rx="3" fill="${color}" data-tt="${tt}"/>`;
      } else {
        const y = P.t + i * rowH + rowH * .16, bh = rowH * .6;
        const bw = (trackW * it.value) / max;
        g += `<text class="lbl-b" x="${P.l - 10}" y="${y + bh / 2 + 3}" text-anchor="end">${esc(it.label)}</text>`;
        g += `<rect x="${P.l}" y="${y}" width="${trackW}" height="${bh}" rx="4" fill="rgba(255,255,255,.045)"/>`;
        g += `<rect class="bar" x="${P.l}" y="${y}" width="${Math.max(2, bw)}" height="${bh}" rx="4" fill="${color}" data-tt="${tt}"/>`;
        g += `<text class="lbl" x="${P.l + bw + 7}" y="${y + bh / 2 + 3}">${value}</text>`;
      }
    });
    return `<svg viewBox="0 0 ${W} ${H}" width="100%" height="100%">${g}</svg>`;
  };
}
function heatmapHtml(data, weeks, channels) {
  const colr = v => {
    if (v < .35) return 'rgba(243,236,221,.72)';
    if (v < .5) return 'rgba(198,161,91,.48)';
    if (v < .65) return 'rgba(198,161,91,.6)';
    return `rgba(198,161,91,${.35 + v * .5})`;
  };
  // --heat-cols drives the CSS grid; on phones the label column shrinks and
  // the cells fit the viewport instead of forcing a sideways scroll.
  let html = `<div class="heat-scroll"><div class="heat-grid" style="--heat-cols:${weeks.length}">`;
  html += `<div></div>` + weeks.map(w => `<div class="heat-lbl" style="text-align:center">${esc(w)}</div>`).join('');
  channels.forEach((ch, r) => {
    html += `<div class="heat-lbl">${esc(ch)}</div>`;
    (data[r] || []).forEach((v, c) => {
      html += `<div class="heat-cell" style="background:${colr(v)}" data-tt="${esc(`<b>${esc(ch)} · ${esc(weeks[c])}</b><br>Sentiment: ${Math.round(v * 100)}/100`)}"></div>`;
    });
  });
  html += '</div></div>';
  return html;
}
