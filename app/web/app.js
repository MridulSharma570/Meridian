/* ------------------------------------------- Phone-friendly data tables ---
   Tables are generated by many views (history, sources, logs, settings,
   comparison). On phones CSS turns each row into a stacked card; the header
   text is copied onto every cell so the value still has a label. A single
   observer on #view decorates tables no matter which view rendered them.
   -------------------------------------------------------------------------- */
function decorateTables(root = document) {
  $$('table', root).forEach(tbl => {
    if (tbl.dataset.mobile === '1') return;
    tbl.dataset.mobile = '1';
    const heads = $$('thead th', tbl).map(th => (th.textContent || '').trim());
    if (!heads.length) tbl.classList.add('no-head');
    $$('tbody tr', tbl).forEach(tr => {
      $$('td', tr).forEach((td, i) => {
        if (!td.hasAttribute('data-label')) td.setAttribute('data-label', heads[i] || '');
      });
    });
  });
}

function watchMobileTables() {
  const view = $('#view');
  if (!view || typeof MutationObserver === 'undefined') return;
  const observer = new MutationObserver(() => decorateTables(view));
  observer.observe(view, { childList: true, subtree: true });
  decorateTables(view);
}

